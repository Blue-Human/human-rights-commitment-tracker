-- Links each recommendation of A/HRC/60/8 to the Sustainable Development Goals and targets of the
-- 2030 Agenda (A/RES/70/1), as tagged by OHCHR in the Universal Human Rights Index (UHRI).
-- HRCT publishes that official tagging as it is: no link is added, removed or reinterpreted.
-- A goal may be linked without a specific target, and 18 recommendations carry no goal at all.
-- Snapshot: data/sdg/uhri-spain-upr4.json (tagging published on the UHRI on 2025-12-30).
-- The rows below are the output of `node scripts/import-uhri-sdg.mjs --sql`.
-- Safe to run again: links are inserted or updated.

create table if not exists public.commitment_sdgs (
  commitment_id uuid not null references public.commitments(id) on delete cascade,
  goal smallint not null check (goal between 1 and 17),
  -- Targets of this goal related to the recommendation, such as {16.3,16.b}. Empty when the
  -- source links the goal as a whole.
  targets text[] not null default '{}',
  source text not null default 'uhri',
  source_published_at date,
  created_at timestamptz not null default now(),
  primary key (commitment_id, goal),
  constraint commitment_sdgs_targets_of_goal check (array_to_string(targets, ' ') ~ ('^(' || goal || '\.([0-9]{1,2}|[a-d])( |$))*$'))
);

alter table public.commitment_sdgs enable row level security;

drop policy if exists commitment_sdgs_public_read on public.commitment_sdgs;
create policy commitment_sdgs_public_read on public.commitment_sdgs for select using (exists (select 1 from public.commitments c where c.id=commitment_id and c.publication_status='published'));

create or replace view public.hrct_public_sdgs with (security_invoker = true) as
select c.public_id, s.goal, s.targets, s.source, s.source_published_at
from public.commitment_sdgs s
join public.commitments c on c.id=s.commitment_id
where c.publication_status='published';

-- New tables and views inherit full default privileges: the public roles only read.
revoke all on public.commitment_sdgs, public.hrct_public_sdgs from anon, authenticated;
grant select on public.commitment_sdgs, public.hrct_public_sdgs to anon, authenticated;

